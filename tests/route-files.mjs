import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
const context=vm.createContext({Date,Number,Math});
vm.runInContext(await readFile(new URL('../assets/route-files.js',import.meta.url),'utf8'),context);
const route=vm.runInContext('DriverManRoute',context);
const a={latitude:-4.325,longitude:15.322,recorded_at:1791453600000,segment_id:'a'};
const b={...a,longitude:15.323,recorded_at:a.recorded_at+10000};
const c={...b,latitude:-4.326,recorded_at:b.recorded_at+10000};
const parts=route.split([[a,b,c,{...c,recorded_at:c.recorded_at+180000}]]);
assert.equal(parts.length,2);
assert.ok(route.stats(parts).meters>210 && route.stats(parts).meters<230);
assert.equal(route.stats(parts).count,4);
assert.equal(route.split([[a,{...b,longitude:170}]]).length,2);
const passiveOptions={maxGapSeconds:route.passiveGapSeconds};
const passive=route.split([[a,{...b,recorded_at:a.recorded_at+300000},{...c,recorded_at:a.recorded_at+600000}]],passiveOptions);
assert.equal(passive.length,1,'Les relevés passifs à cinq minutes restent reliés sur la carte.');
assert.ok(route.stats(passive).meters>210);
assert.equal(route.split([[a,{...b,recorded_at:a.recorded_at+620000}]],passiveOptions).length,1,'Tolérance pour une réception GPS tardive.');
assert.equal(route.split([[a,{...b,recorded_at:a.recorded_at+660000}]],passiveOptions).length,2,'Une vraie interruption reste visible.');
assert.equal(route.split([[a,{...b,longitude:170,recorded_at:a.recorded_at+300000}]],passiveOptions).length,2,'Les sauts GPS restent séparés.');
assert.equal((route.gpx(passive,'GPS passif').match(/<trkseg>/g)||[]).length,1);
const untimed=route.split([[{...a,recorded_at:null},{...b,recorded_at:null}]]);
assert.equal(untimed.length,1);assert.equal(route.stats(untimed).timed,0);
assert.equal(route.split([[a,{latitude:NaN},b]]).length,2);
const gpx=route.gpx(parts,'A&B <course>');
assert.match(gpx,/<name>A&amp;B &lt;course&gt;<\/name>/);
assert.equal((gpx.match(/<trkseg>/g)||[]).length,2);
assert.equal((gpx.match(/<time>/g)||[]).length,4);
assert.doesNotMatch(route.gpx(untimed,'sans heures'),/<time>/);
const kml=route.kml(parts,'GPS');assert.match(kml,/<gx:coord>15.322 -4.325 0<\/gx:coord>/);assert.match(kml,/<when>/);
assert.match(route.kml(untimed,'sans heures'),/<coordinates>15.322,-4.325 15.323,-4.325<\/coordinates>/);
const separated=route.split([[a,b],[{...c,latitude:-4.36,longitude:15.29,segment_id:'b'}]]);
const before=JSON.stringify(separated),measured=route.stats(separated).meters;
const gaps=route.connections(separated);
assert.equal(gaps.length,1,'Deux segments sont reliés visuellement.');
assert.equal(gaps[0][0],b);assert.equal(gaps[0][1],separated[1][0]);
assert.equal(JSON.stringify(separated),before,'La liaison ne change pas les relevés.');
assert.equal(route.stats(separated).meters,measured,'La distance de la liaison est exclue.');
assert.equal((route.gpx(separated,'Test').match(/<trkseg>/g)||[]).length,2);
assert.equal((route.kml(separated,'Test').match(/<Placemark>/g)||[]).length,2);
assert.equal(route.connections([[a],[a]]).length,0,'Pas de liaison entre points identiques.');
assert.equal(route.connections([[a],[],[b]]).length,1);
assert.equal(route.connections([]).length,0);
assert.equal(route.connections([[a]]).length,0);
const crossing=route.coordinates([[{latitude:0,longitude:179.999}],[{latitude:0,longitude:-179.999}]]);
assert.ok(Math.abs(crossing[0][0][1]-crossing[1][0][1])<0.003,'La liaison ne traverse pas tout le monde à l’antéméridien.');
assert.equal(route.connections(crossing).length,1);
const out=new URL('./.artifacts/routes/',import.meta.url);await mkdir(out,{recursive:true});
await writeFile(new URL('course-test.gpx',out),gpx);
await writeFile(new URL('course-test.kml',out),kml);
console.log('Itinéraires : segments, liaisons indicatives sans modification des données/distances, GPX/KML, antéméridien et échappement vérifiés.');
