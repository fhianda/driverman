import assert from 'node:assert/strict';
import {GPS_INTERVAL_MS,PositionQueue} from '../src/queue.js';
let stored=null,clock=1_800_000_000_000,writes=0,offline=false;
const options={read:async()=>structuredClone(stored),write:async value=>{stored=structuredClone(value);writes++;},send:async(id,points)=>{if(offline)throw Error('offline');return{accepted:points.map(p=>p.sample_id)};},now:()=>clock};
const location=()=>({latitude:-4.325,longitude:15.322,accuracy:8,time:clock});
const queue=new PositionQueue(options);await queue.load();
assert.equal(GPS_INTERVAL_MS,15000);
assert.equal(queue.nextSampleAt(1),null);
assert.equal(await queue.add(location(),1,'a'),true,'Premier point au départ.');
const first=clock;
assert.equal(queue.nextSampleAt(1),first+15000);
await queue.flush();assert.equal(queue.points.length,0);
const writesAfterFirst=writes;
clock=first+14999;
assert.equal(await queue.add(location(),1,'a'),false,'Aucun nouveau point à 14,999 s, même après synchronisation.');
assert.equal(writes,writesAfterFirst,'Les callbacks entre deux échéances n’écrivent pas inutilement sur le téléphone.');
const resumed=new PositionQueue(options);await resumed.load();
assert.equal(await resumed.add(location(),1,'b'),false,'Le redémarrage conserve la dernière échéance, même si la file est vide.');
clock=first+15000;
assert.equal(await resumed.add(location(),1,'b'),true,'Relevé exact à 15 secondes, y compris aux mêmes coordonnées.');
clock+=15000;
assert.equal(await resumed.add({...location(),accuracy:100},1,'b'),false);
assert.equal(resumed.nextSampleAt(1),clock,'Un GPS imprécis ne décale pas le prochain relevé.');
clock+=2000;
const both=await Promise.all([resumed.add(location(),1,'b'),resumed.add(location(),1,'b')]);
assert.deepEqual(both,[true,false],'Callbacks concurrents : un seul point pour cette échéance.');
assert.equal(await resumed.add(location(),2,'new-trip'),true,'Une nouvelle course reçoit son propre point de départ.');
offline=true;await assert.rejects(resumed.flush(),/offline/);
const recovering=new PositionQueue(options);await recovering.load();assert.equal(recovering.points.length,3);
clock+=15000;assert.equal(await recovering.add(location(),1,'c'),true,'La collecte continue hors réseau.');
offline=false;await recovering.flush();assert.equal(recovering.points.length,0);
clock+=1000;assert.equal(await recovering.add(location(),1,'c'),false,'La reprise réseau ne déclenche aucun point supplémentaire.');
const checkpoint=structuredClone(stored);
clock+=15000;
const diskFailure=new PositionQueue({...options,write:async()=>{throw Error('disk');}});await diskFailure.load();
await assert.rejects(diskFailure.add(location(),1,'d'),/disk/);
assert.deepEqual(stored,checkpoint,'Échec disque : ni point ni calendrier partiellement enregistré.');
assert.equal(diskFailure.nextSampleAt(1),checkpoint.lastRecordedAt[1]+15000);
stored=[{movement_id:8,sample_id:'legacy',segment_id:'legacy',recorded_at:clock,latitude:-4,longitude:15,accuracy:8}];
const migrated=new PositionQueue(options);await migrated.load();assert.equal(migrated.points.length,1);
await migrated.flush();assert.equal(stored.version,2);assert.equal(stored.lastRecordedAt[8],clock);
assert.equal(await migrated.add(location(),8,'after-upgrade'),false,'La migration conserve le délai depuis le dernier point.');
await assert.rejects(new PositionQueue({...options,read:async()=>({version:99,points:[]})}).load(),/récupéré/);
stored=null;
const ending=new PositionQueue(options);await ending.load();
assert.equal(await ending.add(location(),25,'trip'),true);
clock+=5000;
assert.equal(await ending.add(location(),25,'trip'),false);
assert.equal(await ending.add(location(),25,'trip',{final:true}),true,'Le retour conserve le dernier point avant la prochaine échéance.');
assert.equal(await ending.add(location(),25,'trip',{final:true}),false,'Le point de retour ne crée pas de doublon.');
clock+=1000;
assert.equal(await ending.add({...location(),accuracy:93},25,'trip',{final:true}),false,'Le retour ne contourne pas la précision exigée pour un tracé.');
assert.equal(await ending.add({...location(),simulated:true},25,'trip',{final:true}),false);
assert.equal(await ending.add({...location(),time:clock-31000},25,'trip',{final:true}),false,'Ne pas créer un point de retour avec un ancien relevé.');
assert.equal(ending.points.length,2);
console.log('Collecte passive : premier point, intervalle de 15 secondes, véhicule immobile, persistance après envoi/redémarrage, concurrence, réseau, disque et migration vérifiés.');
